//! Dispatch table emitter — produces `dispatch.cpp`.
//!
//! The dispatch table maps PSP virtual addresses to C++ function pointers.
//! `RECOMP_LOOKUP(vaddr)` uses it for indirect calls and cross-section jumps.
//! Address 0x00000000 maps to a no-op function (safe sentinel for unresolved calls).
//! It is a flat open-addressing table: libc++'s `std::unordered_map` find was the
//! runtime's top function in the 2026-10-29 CPU profile (~4 % of process cycles).
use psp_parser::analysis_json::{JsonFunction, JsonMidEntry};

/// Free slots kept for `psp_dispatch_register` calls made after init (HLE stubs, hooks).
const RUNTIME_REGISTRATIONS: usize = 4096;

/// Table storage + probe (emitted after `kDispatchBits`). Fibonacci hash of the
/// word address, linear probing; one slot always stays empty so probes end.
const DISPATCH_TABLE_CPP: &str = r#"static constexpr uint32_t kDispatchMask = (1u << kDispatchBits) - 1;
static constexpr uint32_t kEmpty = 0xFFFFFFFFu;  // never a 4-aligned code address
static uint32_t s_keys[1u << kDispatchBits];
static FuncPtr s_fns[1u << kDispatchBits];
static uint32_t s_count = 0;

// Slot holding vaddr, or the empty slot where it would go.
static inline uint32_t dispatch_slot(uint32_t vaddr) {
    uint32_t i = ((vaddr >> 2) * 0x9E3779B1u) >> (32 - kDispatchBits);
    while (s_keys[i] != vaddr && s_keys[i] != kEmpty) i = (i + 1) & kDispatchMask;
    return i;
}

"#;

/// Register, init (with a map-semantics self-check) and lookup, emitted after the entries.
const DISPATCH_FUNCS_CPP: &str = r#"// Extern miss handler — provided by the runtime's psp_dispatch.cpp
extern FuncPtr psp_on_lookup_miss(uint32_t vaddr);

// psp_dispatch_register — runtime HLE and hooks replace or add entries (last wins).
void psp_dispatch_register(uint32_t vaddr, FuncPtr fn) {
    const uint32_t i = dispatch_slot(vaddr);
    s_fns[i] = fn;  // before the key: a concurrent lookup never sees a key without its fn
    if (s_keys[i] == kEmpty) {
        if (++s_count >= kDispatchMask) {
            std::fprintf(stderr, "[DISPATCH] FATAL: table full (%u slots)\n", kDispatchMask + 1);
            std::abort();
        }
        s_keys[i] = vaddr;
    }
}

void psp_init_dispatch_table() {
    std::fill(std::begin(s_keys), std::end(s_keys), kEmpty);
    for (const auto& e : k_dispatch_entries) psp_dispatch_register(e.addr, e.fn);
    // Self-check: every address resolves to its LAST table entry, as the old map did.
    std::vector<bool> seen(kDispatchMask + 1);
    for (size_t k = std::size(k_dispatch_entries); k-- > 0;) {
        const auto& e = k_dispatch_entries[k];
        const uint32_t i = dispatch_slot(e.addr);
        if (seen[i]) continue;
        seen[i] = true;
        if (s_keys[i] != e.addr || s_fns[i] != e.fn) {
            std::fprintf(stderr, "[DISPATCH] FATAL: 0x%08X does not resolve to its entry\n", e.addr);
            std::abort();
        }
    }
}

// RECOMP_LOOKUP — the entry point called by emitted indirect calls
FuncPtr RECOMP_LOOKUP(uint32_t vaddr) {
    const uint32_t i = dispatch_slot(vaddr);
    if (s_keys[i] == kEmpty) return psp_on_lookup_miss(vaddr);
    return s_fns[i];
}
"#;

/// Emit the full `dispatch.cpp` file content.
///
/// `functions`: all decoded functions (from analysis.json).
/// `mid_entries`: mid-function entry wrappers (generated in Plan 02-06).
/// Returns the complete C++ source as a `String`.
pub fn emit_dispatch_table(
    functions: &[JsonFunction],
    mid_entries: &[JsonMidEntry],
    module_name: &str,
    name_overrides: &std::collections::HashMap<u32, String>,
) -> String {
    let _ = module_name; // used by caller for naming context
    let mut out = String::with_capacity(functions.len() * 60 + 4096);
    out.push_str("// Generated by psprecomp — do not edit\n");
    out.push_str("#include \"recomp.h\"\n");
    out.push_str("#include \"funcs.h\"\n");
    out.push_str("#include <algorithm>\n#include <cstdio>\n#include <cstdlib>\n#include <iterator>\n#include <vector>\n\n");
    out.push_str("using FuncPtr = void(*)(uint8_t*, recomp_context*);\n\n");
    out.push_str("static void noop_func(uint8_t*, recomp_context*) {}\n\n");
    // Capacity: 2x the entries (sentinel included) plus the runtime registrations.
    let slots = 2 * (functions.len() + mid_entries.len() + 1 + RUNTIME_REGISTRATIONS);
    let bits = slots.next_power_of_two().trailing_zeros();
    out.push_str(&format!("static constexpr uint32_t kDispatchBits = {bits};\n"));
    out.push_str(DISPATCH_TABLE_CPP);

    // Entries are emitted as a constant table walked by a loop: one assignment
    // statement per entry (~20k for Patapon 3) makes clang's -O2 pipeline
    // effectively hang on a single giant function. Table order is preserved,
    // so a later entry for the same address still overwrites an earlier one.
    out.push_str("static const struct { uint32_t addr; FuncPtr fn; } k_dispatch_entries[] = {\n");
    // Leading sentinel keeps the array non-empty when there are no functions.
    out.push_str("    {0x00000000U, noop_func},\n");
    for func in functions {
        let addr: u32 = u64::from_str_radix(
            func.address.trim_start_matches("0x"), 16
        ).unwrap_or(0) as u32;
        // Use deduplicated name if available, otherwise sanitize the original
        let cpp_name = name_overrides
            .get(&addr)
            .map(|n| crate::sanitize::sanitize_identifier(n))
            .unwrap_or_else(|| crate::sanitize::sanitize_identifier(&func.name));
        out.push_str(&format!("    {{0x{addr:08X}U, {cpp_name}}},\n"));
    }

    // Mid-entry wrappers (generated by Plan 02-06's emit_mid_entry_wrappers)
    for me in mid_entries {
        let addr: u32 = u64::from_str_radix(
            me.addr.trim_start_matches("0x"), 16
        ).unwrap_or(0) as u32;
        out.push_str(&format!("    {{0x{addr:08X}U, func_{addr:08X}_entry}},\n"));
    }
    out.push_str("};\n\n");

    out.push_str(DISPATCH_FUNCS_CPP);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn dispatch_contains_noop() {
        let result = emit_dispatch_table(&[], &[], "test", &std::collections::HashMap::new());
        assert!(result.contains("{0x00000000U, noop_func},"));
        assert!(result.contains("RECOMP_LOOKUP"));
    }

    fn funcs(n: u32) -> Vec<JsonFunction> {
        (0..n)
            .map(|i| JsonFunction {
                name: format!("FUN_{:08x}", 0x0880_4000 + i * 4),
                address: format!("0x{:08X}", 0x0880_4000 + i * 4),
                size: 4,
                is_external: false,
                is_thunk: false,
                source: "ghidra".to_string(),
            })
            .collect()
    }

    #[test]
    fn dispatch_uses_flat_table() {
        let result = emit_dispatch_table(&funcs(3), &[], "test", &std::collections::HashMap::new());
        assert!(result.contains("kEmpty = 0xFFFFFFFFu"), "{result}");
        assert!(!result.contains("unordered_map"), "{result}");
    }

    #[test]
    fn dispatch_capacity_has_headroom() {
        // 2 x (10 functions + sentinel + 4096 runtime registrations) = 8214 -> 2^14.
        let result = emit_dispatch_table(&funcs(10), &[], "test", &std::collections::HashMap::new());
        assert!(result.contains("kDispatchBits = 14;"), "{result}");
    }

    #[test]
    fn dispatch_miss_calls_extern_handler() {
        let result = emit_dispatch_table(&[], &[], "test", &std::collections::HashMap::new());
        assert!(
            result.contains("psp_on_lookup_miss"),
            "miss path must call psp_on_lookup_miss"
        );
        assert!(
            result.contains("extern FuncPtr psp_on_lookup_miss"),
            "must declare extern psp_on_lookup_miss"
        );
        assert!(
            !result.contains("return noop_func;"),
            "miss path must NOT return noop_func directly"
        );
    }

    #[test]
    fn dispatch_entries_are_a_const_table() {
        let funcs = vec![JsonFunction {
            name: "FUN_08804000".to_string(),
            address: "0x08804000".to_string(),
            size: 8,
            is_external: false,
            is_thunk: false,
            source: "ghidra".to_string(),
        }];
        let result = emit_dispatch_table(&funcs, &[], "test", &std::collections::HashMap::new());
        assert!(result.contains("k_dispatch_entries[] = {"), "{result}");
        assert!(result.contains("{0x08804000U, FUN_08804000},"), "{result}");
        assert!(result.contains("for (const auto& e : k_dispatch_entries) psp_dispatch_register(e.addr, e.fn);"));
        // No per-entry statements (they make clang -O2 crawl on ~20k entries).
        assert!(!result.contains("psp_dispatch_register(0x08804000U"), "{result}");
    }

    #[test]
    fn empty_dispatch_table_has_sentinel() {
        let result = emit_dispatch_table(&[], &[], "test", &std::collections::HashMap::new());
        assert!(result.contains("k_dispatch_entries[] = {\n    {0x00000000U, noop_func},\n};"), "{result}");
    }
}
